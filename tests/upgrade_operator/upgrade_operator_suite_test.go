const (
	// EnvUpgradeFromVersion overrides the release the test upgrades from, for example "v1.33.1"
	EnvUpgradeFromVersion = "M_UPGRADE_FROM_VERSION"
	repository            = "https://github.com/k8ssandra/cass-operator.git"
	previousDir           = "upgrade_operator/previous"
	operatorDeployment    = "cass-operator-controller-manager"
)

var (
	testName   = "Upgrade Operator"
	namespace  = "test-upgrade-operator"
	dcName     = "dc1"
	dcYaml     = "../testdata/default-three-rack-three-node-dc.yaml"
	dcResource = fmt.Sprintf("CassandraDatacenter/%s", dcName)
	ns         = ginkgo_util.NewWrapper(testName, namespace)
)

func TestLifecycle(t *testing.T) {
	ginkgo_util.RunTestLifecycle(t, testName, ns)
}

// currentVersion returns the VERSION of the build under test from the Makefile, for example "v1.34.0"
func currentVersion() string {
	makefile, err := os.ReadFile(filepath.Join("..", "..", "Makefile"))
	Expect(err).ToNot(HaveOccurred())
	m := regexp.MustCompile(`(?m)^VERSION \?= (\S+)$`).FindStringSubmatch(string(makefile))
	Expect(m).ToNot(BeNil(), "no VERSION in the Makefile")
	return "v" + m[1]
}

// previousRelease returns the newest release tag that is older than the build under test
func previousRelease() string {
	if version := os.Getenv(EnvUpgradeFromVersion); version != "" {
		return version
	}

	current := currentVersion()
	out, err := shutil.Output("git", "ls-remote", "--tags", "--refs", repository)
	Expect(err).ToNot(HaveOccurred())

	previous := ""
	for _, line := range strings.Split(out, "\n") {
		fields := strings.Fields(line)
		if len(fields) != 2 {
			continue
		}
		tag := strings.TrimPrefix(fields[1], "refs/tags/")
		if !semver.IsValid(tag) || semver.Prerelease(tag) != "" || semver.Build(tag) != "" || semver.Canonical(tag) != tag {
			continue
		}
		if semver.Compare(tag, current) < 0 && (previous == "" || semver.Compare(tag, previous) > 0) {
			previous = tag
		}
	}
	Expect(previous).ToNot(BeEmpty(), "no release older than %s", current)
	return previous
}

func installPreviousRelease(version string) {
	By("install cass-operator " + version)
	// The test template moves the operator to the test namespace and rewrites the webhook certificate's
	// dnsNames to match it, use it with the released deployment as the resource
	template, err := os.ReadFile(filepath.Join("..", "kustomize", "kustomization.yaml"))
	Expect(err).ToNot(HaveOccurred())
	kustomization := regexp.MustCompile(`(?m)^namespace: .*$`).
		ReplaceAllString(string(template), "namespace: "+namespace)
	local := "- ../../config/deployments/default\n"
	Expect(kustomization).To(ContainSubstring(local))
	kustomization = strings.Replace(kustomization, local,
		fmt.Sprintf("- github.com/k8ssandra/cass-operator/config/deployments/default?ref=%s\n", version), 1)
	kustomization = "# Generated by the upgrade_operator test from tests/kustomize/kustomization.yaml\n" + kustomization
	Expect(os.WriteFile(filepath.Join("previous", "kustomization.yaml"), []byte(kustomization), 0o644)).To(Succeed())
	Expect(kustomize.DeployDir(namespace, previousDir)).To(Succeed())
}

func operatorPodName() string {
	k := kubectl.Get("pods").
		WithLabel("name=cass-operator").
		FormatOutput(`jsonpath={.items[*].metadata.name}`)
	names := strings.Fields(ns.OutputPanic(k))
	Expect(names).To(HaveLen(1))
	return names[0]
}

func operatorImage() string {
	k := kubectl.Get("deployment", operatorDeployment).
		FormatOutput(`jsonpath={.spec.template.spec.containers[?(@.name=='manager')].image}`)
	return ns.OutputPanic(k)
}

var _ = Describe(testName, func() {
	Context("when upgrading the Cass Operator from the previous release", func() {
		Specify("the datacenter stays available and is not restarted until the update is allowed", func() {
			previous := previousRelease()
			installPreviousRelease(previous)
			ns.WaitForOperatorReady()

			oldOperatorPod := operatorPodName()
			oldOperatorImage := operatorImage()
			Expect(oldOperatorImage).To(HaveSuffix(":" + previous))

			step := "creating a datacenter resource with 3 racks/3 nodes"
			testFile, err := ginkgo_util.CreateTestFile(dcYaml)
			Expect(err).ToNot(HaveOccurred())
			ns.ExecAndLog(step, kubectl.ApplyFiles(testFile))

			ns.WaitForDatacenterReady(dcName)
			ns.WaitForDatacenterCondition(dcName, "Ready", string(corev1.ConditionTrue))
			ns.ExpectDoneReconciling(dcName)
			before := ns.GetDatacenterState(dcName)
			// Problems of the previous release are not this build's, check the invariants after the upgrade only
			ns.ResetEventCheckpoint(dcName)

			sampler := ns.SampleAvailability(dcName)

			By("upgrade cass-operator to the build under test")
			Expect(kustomize.Deploy(namespace)).To(Succeed())

			Expect(operatorImage()).ToNot(Equal(oldOperatorImage))
			step = "wait for the operator Deployment to roll out"
			ns.ExecAndLog(step, kubectl.KCmd{Command: "rollout", Args: []string{"status", "deployment/" + operatorDeployment, "--timeout=300s"}})

			step = "wait for the previous operator pod to be removed"
			k := kubectl.Get("pods").WithFlag("field-selector", fmt.Sprintf("metadata.name=%s", oldOperatorPod))
			ns.WaitForOutputAndLog(step, k, "", 120)
			ns.WaitForOperatorReady()

			ns.WaitForDatacenterReady(dcName)
			ns.AssertDatacenterInvariants(dcName)
			sampler.Stop()
			afterUpgrade := ns.GetDatacenterState(dcName)
			if maps.Equal(before.UpdateRevisions, afterUpgrade.UpdateRevisions) {
				By("the StatefulSets did not change, no pod may have restarted")
				Expect(afterUpgrade.PodUIDs).To(Equal(before.PodUIDs))
			} else {
				By("the StatefulSets changed without an allowed update, they must have been rolled one pod at a time")
			}
			ns.ExpectSameHostIDs(dcName, before)

			// Allow the new operator to update the StatefulSets, as an operator upgrade that changes the
			// default images does
			sampler = ns.SampleAvailability(dcName)
			step = "allow the operator to update the StatefulSets once"
			ns.ExecAndLog(step, kubectl.Annotate("CassandraDatacenter", dcName, api.UpdateAllowedAnnotation, string(api.AllowUpdateOnce)))

			step = "wait for the operator to remove the autoupdate-spec annotation"
			json := `jsonpath={.metadata.annotations.cassandra\.datastax\.com/autoupdate-spec}`
			ns.WaitForOutputAndLog(step, kubectl.Get(dcResource).FormatOutput(json), "", 1200)

			ns.WaitForDatacenterReady(dcName)
			ns.WaitForDatacenterCondition(dcName, string(api.DatacenterRequiresUpdate), string(corev1.ConditionFalse))
			ns.AssertDatacenterInvariants(dcName)
			sampler.Stop()
			ns.ExpectSameHostIDs(dcName, before)

			step = "deleting the dc"
			ns.ExecAndLog(step, kubectl.DeleteFromFiles(testFile))
			ns.AssertDatacenterDeleted(dcName)
		})
	})
})
